#!/usr/bin/env ruby
# frozen_string_literal: true

# Regenerates _data/bibliography.yml (cite key -> JHEP-formatted HTML) from
# mycv/own-bib.bib with mycv/JHEP.bst. Run after editing own-bib.bib:
#   ruby _scripts/bib_to_data.rb

require "cgi"
require "fileutils"
require "open3"
require "tmpdir"
require "yaml"

ROOT = File.expand_path("..", __dir__)
CV_DIR = File.join(ROOT, "mycv")
OUT_FILE = File.join(ROOT, "_data", "bibliography.yml")

ACCENTS = {
  "'" => "\u0301", "`" => "\u0300", '"' => "\u0308", "^" => "\u0302", "~" => "\u0303",
  "=" => "\u0304", "." => "\u0307", "c" => "\u0327", "v" => "\u030C", "u" => "\u0306",
  "H" => "\u030B", "r" => "\u030A", "k" => "\u0328"
}.freeze

DECLARATIONS = {
  "bfseries" => ["<strong>", "</strong>"],
  "ttfamily" => ["<code>", "</code>"],
  "itshape" => ["<em>", "</em>"],
  "em" => ["<em>", "</em>"],
  "scshape" => ['<span style="font-variant: small-caps">', "</span>"]
}.freeze

WRAPPERS = { "textbf" => "strong", "emph" => "em", "textit" => "em", "texttt" => "code" }.freeze

SYMBOLS = {
  "textendash" => "\u2013", "textemdash" => "\u2014", "ss" => "\u00DF", "o" => "\u00F8",
  "O" => "\u00D8", "ae" => "\u00E6", "AE" => "\u00C6", "aa" => "\u00E5", "AA" => "\u00C5",
  "l" => "\u0142", "L" => "\u0141", "i" => "\u0131", "j" => "\u0237", "ldots" => "\u2026",
  "dots" => "\u2026", "newblock" => " "
}.freeze

# Returns [text inside the balanced group starting at s[i], index after it].
def read_group(s, i)
  raise "expected '{' at #{i}" unless s[i] == "{"

  depth = 0
  j = i
  while j < s.length
    case s[j]
    when "\\" then j += 1
    when "{" then depth += 1
    when "}"
      depth -= 1
      return [s[(i + 1)...j], j + 1] if depth.zero?
    end
    j += 1
  end
  raise "unbalanced braces"
end

def skip_ws(s, j)
  j += 1 while j < s.length && s[j] =~ /\s/
  j
end

def accent_argument(s, j)
  if s[j] == "{"
    inner, j = read_group(s, j)
    [inner.sub(/\A\\([ij])\z/, '\1'), j]
  elsif s[j] == "\\"
    name = s[(j + 1)..][/\A[A-Za-z]+/].to_s
    [name.match?(/\A[ij]\z/) ? name : "", j + 1 + name.length]
  else
    [s[j].to_s, j + 1]
  end
end

def command(s, i, out, key)
  j = i + 1
  if s[j].to_s =~ /[A-Za-z]/
    name = s[j..][/\A[A-Za-z]+/]
    j += name.length
    word = true
  else
    name = s[j].to_s
    j += 1
    word = false
  end

  if name == "href"
    url, j = read_group(s, skip_ws(s, j))
    text, j = read_group(s, skip_ws(s, j))
    out << %(<a href="#{CGI.escapeHTML(url.gsub(/\s+/, ''))}">#{convert(text, key)}</a>)
  elsif WRAPPERS.key?(name)
    arg, j = read_group(s, skip_ws(s, j))
    tag = WRAPPERS[name]
    out << "<#{tag}>#{convert(arg, key)}</#{tag}>"
  elsif ACCENTS.key?(name)
    j = skip_ws(s, j) if word
    arg, j = accent_argument(s, j)
    out << CGI.escapeHTML((arg + ACCENTS[name]).unicode_normalize(:nfc))
  elsif SYMBOLS.key?(name)
    out << SYMBOLS[name]
    j = skip_ws(s, j) if word
    j += 2 if s[j, 2] == "{}"
  elsif ["&", "%", "$", "#", "_", "{", "}"].include?(name)
    out << CGI.escapeHTML(name)
  elsif name == " "
    out << " "
  else
    warn "#{key}: unsupported LaTeX command \\#{name}"
  end
  j
end

def group(inner, key)
  m = inner.match(/\A\\(#{DECLARATIONS.keys.join('|')})(?![A-Za-z])\s*/)
  return convert(inner, key) unless m

  open_tag, close_tag = DECLARATIONS[m[1]]
  "#{open_tag}#{convert(m.post_match, key)}#{close_tag}"
end

def convert(s, key)
  out = +""
  i = 0
  while i < s.length
    c = s[i]
    if c == "\\"
      i = command(s, i, out, key)
    elsif c == "{"
      inner, i = read_group(s, i)
      out << group(inner, key)
    elsif c == "~"
      out << "&nbsp;"
      i += 1
    elsif c == "-"
      run = s[i..][/\A-+/]
      out << { 1 => "-", 2 => "\u2013", 3 => "\u2014" }.fetch(run.length, run)
      i += run.length
    elsif c =~ /\s/
      out << " "
      i += 1
    else
      out << CGI.escapeHTML(c)
      i += 1
    end
  end
  out
end

entries = {}
Dir.mktmpdir("bib") do |dir|
  FileUtils.cp([File.join(CV_DIR, "JHEP.bst"), File.join(CV_DIR, "own-bib.bib")], dir)
  File.write(File.join(dir, "bib.aux"), "\\relax\n\\citation{*}\n\\bibstyle{JHEP}\n\\bibdata{own-bib}\n")
  log, = Open3.capture2e("bibtex", "bib", chdir: dir)
  bbl_path = File.join(dir, "bib.bbl")
  abort "bibtex produced no .bbl:\n#{log}" unless File.exist?(bbl_path)
  warn log if log =~ /error message|Repeated entry|I couldn't open/

  bbl = File.read(bbl_path)
  pattern = /\\bibitem\{([^}]+)\}\{([^}]+)\}(?=\{)/
  pos = 0
  while (m = pattern.match(bbl, pos))
    body, pos = read_group(bbl, m.end(0))
    entries[m[1]] = convert(body, m[1]).gsub(/\s+/, " ").strip
  end
end

abort "No entries parsed" if entries.empty?

FileUtils.mkdir_p(File.dirname(OUT_FILE))
header = "# Generated by _scripts/bib_to_data.rb from mycv/own-bib.bib; do not edit.\n"
File.write(OUT_FILE, header + entries.to_yaml(line_width: -1))
puts "Wrote #{entries.size} entries to #{OUT_FILE}"
